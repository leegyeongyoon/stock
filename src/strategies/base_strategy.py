"""Base strategy class and common interfaces."""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import date, datetime
from typing import Optional

import pandas as pd
import pandas_ta as ta

from src.config.constants import SignalType, DEFAULT_STOP_LOSS, DEFAULT_TAKE_PROFIT


@dataclass
class StrategyConfig:
    """Strategy configuration parameters."""

    name: str
    stop_loss: float = DEFAULT_STOP_LOSS
    take_profit: float = DEFAULT_TAKE_PROFIT
    max_holding_days: Optional[int] = None
    params: dict = field(default_factory=dict)


@dataclass
class TradeSignal:
    """Trading signal generated by a strategy."""

    code: str
    signal_type: SignalType
    price: int
    date: datetime
    strategy_name: str
    reason: str
    strength: float = 1.0  # Signal strength (0-1)

    def to_dict(self) -> dict:
        """Convert to dictionary."""
        return {
            "code": self.code,
            "signal_type": self.signal_type.value,
            "price": self.price,
            "date": self.date,
            "strategy_name": self.strategy_name,
            "reason": self.reason,
            "strength": self.strength,
        }


class BaseStrategy(ABC):
    """Abstract base class for all trading strategies."""

    def __init__(self, config: StrategyConfig):
        """
        Initialize strategy.

        Args:
            config: Strategy configuration.
        """
        self.config = config
        self.name = config.name

    @abstractmethod
    def generate_signals(
        self,
        df: pd.DataFrame,
        code: str,
    ) -> list[TradeSignal]:
        """
        Generate trading signals for a stock.

        Args:
            df: OHLCV DataFrame with index as date.
            code: Stock code.

        Returns:
            List of trading signals.
        """
        pass

    def should_exit(
        self,
        entry_price: int,
        current_price: int,
        entry_date: datetime,
        current_date: datetime,
        df: pd.DataFrame,
    ) -> tuple[bool, str]:
        """
        Check if position should be exited.

        Returns:
            Tuple of (should_exit, reason).
        """
        pnl_rate = (current_price - entry_price) / entry_price

        # Stop loss
        if pnl_rate <= -self.config.stop_loss:
            return True, f"Stop loss triggered: {pnl_rate:.2%}"

        # Take profit
        if pnl_rate >= self.config.take_profit:
            return True, f"Take profit triggered: {pnl_rate:.2%}"

        # Max holding days
        if self.config.max_holding_days:
            holding_days = (current_date - entry_date).days
            if holding_days >= self.config.max_holding_days:
                return True, f"Max holding days reached: {holding_days} days"

        return False, ""

    @staticmethod
    def add_technical_indicators(df: pd.DataFrame) -> pd.DataFrame:
        """Add common technical indicators to DataFrame."""
        df = df.copy()

        # Moving Averages
        df["ma5"] = ta.sma(df["close"], length=5)
        df["ma10"] = ta.sma(df["close"], length=10)
        df["ma20"] = ta.sma(df["close"], length=20)
        df["ma60"] = ta.sma(df["close"], length=60)
        df["ma120"] = ta.sma(df["close"], length=120)

        # Exponential Moving Averages
        df["ema5"] = ta.ema(df["close"], length=5)
        df["ema20"] = ta.ema(df["close"], length=20)

        # RSI
        df["rsi"] = ta.rsi(df["close"], length=14)

        # Bollinger Bands
        try:
            bbands = ta.bbands(df["close"], length=20, std=2)
            if bbands is not None and not bbands.empty:
                # Handle different column naming conventions
                upper_cols = [c for c in bbands.columns if "BBU" in c or "upper" in c.lower()]
                middle_cols = [c for c in bbands.columns if "BBM" in c or "middle" in c.lower()]
                lower_cols = [c for c in bbands.columns if "BBL" in c or "lower" in c.lower()]

                if upper_cols and middle_cols and lower_cols:
                    df["bb_upper"] = bbands[upper_cols[0]]
                    df["bb_middle"] = bbands[middle_cols[0]]
                    df["bb_lower"] = bbands[lower_cols[0]]
                    df["bb_width"] = (df["bb_upper"] - df["bb_lower"]) / df["bb_middle"]
        except Exception:
            # Fallback: calculate manually
            df["bb_middle"] = df["close"].rolling(window=20).mean()
            rolling_std = df["close"].rolling(window=20).std()
            df["bb_upper"] = df["bb_middle"] + (rolling_std * 2)
            df["bb_lower"] = df["bb_middle"] - (rolling_std * 2)
            df["bb_width"] = (df["bb_upper"] - df["bb_lower"]) / df["bb_middle"]

        # MACD
        macd = ta.macd(df["close"])
        if macd is not None:
            df["macd"] = macd["MACD_12_26_9"]
            df["macd_signal"] = macd["MACDs_12_26_9"]
            df["macd_hist"] = macd["MACDh_12_26_9"]

        # Volume indicators
        df["volume_ma20"] = ta.sma(df["volume"], length=20)
        df["volume_ratio"] = df["volume"] / df["volume_ma20"]

        # ATR (Average True Range)
        df["atr"] = ta.atr(df["high"], df["low"], df["close"], length=14)

        # Stochastic
        stoch = ta.stoch(df["high"], df["low"], df["close"])
        if stoch is not None:
            df["stoch_k"] = stoch["STOCHk_14_3_3"]
            df["stoch_d"] = stoch["STOCHd_14_3_3"]

        # Price change
        df["change"] = df["close"].pct_change()
        df["change_1d"] = df["change"]
        df["change_5d"] = df["close"].pct_change(5)
        df["change_20d"] = df["close"].pct_change(20)

        # High/Low
        df["high_52w"] = df["high"].rolling(window=252).max()
        df["low_52w"] = df["low"].rolling(window=252).min()

        # Previous day values
        df["prev_close"] = df["close"].shift(1)
        df["prev_high"] = df["high"].shift(1)
        df["prev_low"] = df["low"].shift(1)

        # Gap
        df["gap"] = (df["open"] - df["prev_close"]) / df["prev_close"]

        # Candle patterns
        df["is_bullish"] = df["close"] > df["open"]
        df["is_bearish"] = df["close"] < df["open"]
        df["body_size"] = abs(df["close"] - df["open"]) / df["open"]

        return df

    @staticmethod
    def calculate_vwap(df: pd.DataFrame) -> pd.Series:
        """Calculate VWAP (Volume Weighted Average Price)."""
        typical_price = (df["high"] + df["low"] + df["close"]) / 3
        vwap = (typical_price * df["volume"]).cumsum() / df["volume"].cumsum()
        return vwap

    def get_strategy_info(self) -> dict:
        """Get strategy information."""
        return {
            "name": self.name,
            "stop_loss": self.config.stop_loss,
            "take_profit": self.config.take_profit,
            "max_holding_days": self.config.max_holding_days,
            "params": self.config.params,
        }
